#!/usr/bin/env python3
"""Read-only MIPS J/JAL audit of candidate CDEF overlay entry points."""
import argparse
import json
from pathlib import Path

SYNC = b'\x00' + b'\xff'*10 + b'\x00'
BASE = 0x8017c000
REGIONS = (0x38000, 0x3c000)
ENTRIES = (0x7f8, 0x84c)

def decode_jump(word, pc):
    op = word >> 26
    if op not in (2, 3):
        return None
    target = ((pc + 4) & 0xf0000000) | ((word & 0x03ffffff) << 2)
    return {'op': 'JAL' if op == 3 else 'J', 'target': f'0x{target:08X}'}

def scan_region(data, start, base=BASE, window=0x60):
    if window <= 0 or window % 4:
        raise ValueError('window must be positive and word-aligned')
    result = {}
    for entry in ENTRIES:
        p = start + entry
        if p + window > len(data):
            raise ValueError('entry scan would exceed file extent')
        calls = []
        for offset in range(0, window, 4):
            word = int.from_bytes(data[p+offset:p+offset+4], 'little')
            decoded = decode_jump(word, base+entry+offset)
            if decoded is not None:
                target = int(decoded['target'], 16)
                decoded.update({'offset_in_region': f'0x{entry+offset:X}',
                                'class': 'candidate_overlay' if base <= target < base+0x4000
                                else 'external'})
                calls.append(decoded)
        result[f'0x{base+entry:08X}'] = calls
    return result

def read_cdef(image, entry):
    out = bytearray()
    with open(image, 'rb') as stream:
        for i in range((entry['size'] + 2047)//2048):
            stream.seek((entry['lba']+i)*2352)
            sec = stream.read(2352)
            if (len(sec) != 2352 or sec[:12] != SYNC or sec[15] != 2
                    or sec[18] & 0x20 or sec[16:20] != sec[20:24]):
                raise ValueError('invalid raw MODE2/Form1 sector')
            out.extend(sec[24:2072])
    return bytes(out[:entry['size']])

def audit(data):
    results = [scan_region(data, start) for start in REGIONS]
    return {'candidate_base': f'0x{BASE:08X}', 'copies_equal': results[0]==results[1],
            'entry_flow': results[0], 'window_bytes_per_entry': 0x60}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('image')
    ap.add_argument('inventory', help='JSON generated by inspect_disc.py --json')
    args = ap.parse_args()
    entries = json.loads(Path(args.inventory).read_text(encoding='utf8'))['entries']
    selected = [e for e in entries if e['path']=='/BIN/CDEF.BIN;1' and not e['directory']]
    if len(selected) != 1:
        ap.error('CDEF.BIN not found')
    print(json.dumps(audit(read_cdef(args.image, selected[0])), indent=2))

if __name__ == '__main__':
    main()
